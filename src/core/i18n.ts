let currentLocale: Locale = 'id';

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  localStorage.setItem('app-locale', locale);
  document.documentElement.lang = locale;
}

export function getLocale(): Locale {
  return currentLocale;
}

export function initLocale(): void {
  const saved = localStorage.getItem('app-locale') as Locale | null;
  if (saved && (saved === 'id' || saved === 'en')) {
    currentLocale = saved;
  } else {
    // Detect from browser
    const browserLang = navigator.language.startsWith('id') ? 'id' : 'en';
    currentLocale = browserLang;
  }
  document.documentElement.lang = currentLocale;
}

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  let translation = translations[currentLocale]?.[key] || translations.en[key] || key;
  
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      translation = translation.replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v));
    });
  }
  
  return translation;
}

// Helper for pluralization (simple)
export function tPlural(key: TranslationKey, count: number, params?: Record<string, string | number>): string {
  const baseParams = { ...params, count };
  return t(key, baseParams);
}

